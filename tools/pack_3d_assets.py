#!/usr/bin/env python3
"""Pack every 3D asset and the art direction around it into one zip for a
design session elsewhere (docs/BLENDER_101.md §27):

    python3 tools/pack_3d_assets.py            # → ~/Desktop/hoop_shoot_3d_assets_1_areas.zip, _2_props_balls.zip, _3_sources.zip
    python3 tools/pack_3d_assets.py outdir     # anywhere else

Three zips, each under the 20 MB upload limit of the design sessions, each
carrying README.md and docs/ so any one of them stands alone.

Models (glb), their textures and set resources, the Blender sources and the
build scripts that generate them, the third-party pack with its credits, the
real-court snapshots, docs/BLENDER_101.md, a README with the art direction,
and a generated geometry sheet pulled from core/physics/sim_geometry.gd and
the arena_set.tres files so the numbers never drift. No audio, no .import
sidecars, no .blend1 backups. Re-run it after the next area lands.
"""
import os
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NAME = "hoop_shoot_3d_assets"
## The parts (every one gets README.md + docs/): each must stay under the upload cap.
PARTS = [
    ("1_areas", ["areas", "hoops", "textures"]),
    ("2_props_balls", ["balls", "props"]),
    ("3_sources", ["source", "third_party"]),
]
PART_CAP_MB = 19.5
SKIP_SUFFIX = (".import", ".blend1", ".ogg", ".wav", ".mp3", ".uid", ".pyc")
SKIP_DIRS = {"ambience", "sfx", "__pycache__"}


def copy_tree(src: Path, dst: Path, keep=None) -> int:
    """Copy src into dst skipping audio, sidecars and backups. Returns files copied."""
    n = 0
    for p in sorted(src.rglob("*")):
        rel = p.relative_to(src)
        if any(part in SKIP_DIRS for part in rel.parts):
            continue
        if p.is_dir() or p.suffix in SKIP_SUFFIX:
            continue
        if keep is not None and not keep(p):
            continue
        out = dst / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(p, out)
        n += 1
    return n


def copy_files(paths, dst: Path) -> int:
    dst.mkdir(parents=True, exist_ok=True)
    n = 0
    for p in paths:
        if p.exists() and p.suffix not in SKIP_SUFFIX:
            shutil.copy2(p, dst / p.name)
            n += 1
    return n


# ---- the geometry sheet, from the code --------------------------------------------------

def gd_const(src: str, name: str):
    m = re.search(r"^const %s\s*:?=\s*(.+?)\s*$" % re.escape(name), src, re.M)
    return m.group(1) if m else None


def geometry_md() -> str:
    sg = (ROOT / "core/physics/sim_geometry.gd").read_text()
    sc = (ROOT / "core/physics/sim_constants.gd").read_text()
    rim_e = float(gd_const(sg, "ARCADE_RIM_E"))
    beach_e = rim_e * 1.33
    city_e = beach_e * 1.15
    cage_dist = 2.9      # App.ARCADE_HOOP_DIST (the mode's dist; the recipe's default is 2.6 for tests)
    beach_dist = 2.9 * 1.175
    city_dist = 2.9 * 1.25
    park_dist = 3.70
    park_e = 0.60
    half_w = float(gd_const(sc, "BOARD_HALF_W"))
    r_rim = float(gd_const(sc, "R_RIM"))
    r_ball = float(gd_const(sc, "R_BALL"))
    rows = [
        ("Arcade cage", cage_dist, rim_e, 0.61, 0.76, "mesh walls z ±1.26, front lip x −1.8, back x 4.4, roof 3.9; return ramp under the hoop; no prop boxes"),
        ("Beach", beach_dist, beach_e, half_w, 1.05, "fence x −11.2…5.7, z ±8.6; in-ground pole r 0.06 at +0.3 behind the board; nylon net"),
        ("City court", city_dist, city_e, half_w, 1.05, "same fence and pole; chain net; prop boxes: one floor speaker (x 4.32–4.78, z −1.75 ±0.26, 0.92 tall) and the tabletop scoreboard (x 5.20–5.65, z 1.45 ±0.38, 0.56 tall)"),
        ("Park", park_dist, park_e, 0.70, 1.05, "no fence: soft walls at the slab's edge x −7.0…4.70, z ±6.0 (restitution 0.2); in-ground pole r 0.07 at +0.17; nylon net; prop box: the snow drift at the pole's foot (x 4.05–4.50, z ±0.40, 0.18 tall)"),
    ]
    out = ["# Court geometry (generated by tools/pack_3d_assets.py from core/physics/sim_geometry.gd)", "",
           "Metres. The shooter stands at x 0 and throws toward +x; y is up; z is sideways (right-hand",
           "rule, +z to the shooter's left as drawn in Blender's build scripts via `s2b`). Every court shares",
           "the rim height, the release height and the arcade rim feel; they differ in distance, the",
           "iron's bounce and the board.", "",
           "| Court | Hoop distance (m) | Rim height | Release height | Rim restitution | Board half-width × height | Board bottom below rim | Enclosure / props |",
           "|---|---|---|---|---|---|---|---|"]
    for name, dist, e, hw, bh, note in rows:
        out.append("| %s | %.2f | 2.44 | 1.85 | %.3f | %.2f × %.2f | 0.15 | %s |" % (name, dist, e, hw, bh, note))
    out += ["", "Rim radius %.4f m, ball radius %.3f m. The bracket runs from the rim's back edge to the board;" % (r_rim, r_ball),
            "`net_exit_y` is rim − 0.6. The last 30 s of a cage trial move the board (Lissajous 1:2,",
            "depth 2.4 ↔ 3.4 m over 12 s, ±0.4 m lateral); the beach and city shuffle the shooting spot instead.", "",
            "## Shooting spots and title poses (from each arena_set.tres)", ""]
    for area in ("cage", "beach", "park", "city"):
        t = (ROOT / "assets/arena" / area / "arena_set.tres").read_text()
        def field(k):
            m = re.search(r"^%s = (.+)$" % k, t, re.M)
            return m.group(1) if m else "—"
        out.append("### %s" % field("display_name").strip('"'))
        out.append("")
        names = re.findall(r'"([^"]+)"', field("spot_names")) if field("spot_names") != "—" else []
        pos = re.findall(r"[-\d.]+", field("spot_positions").replace("PackedVector3Array", "")) if field("spot_positions") != "—" else []
        if names:
            out.append("Spots (x, y, z): " + ", ".join("%s (%s, %s, %s)" % (n, pos[3 * i], pos[3 * i + 1], pos[3 * i + 2]) for i, n in enumerate(names)))
        else:
            out.append("Spots: the key only (the cage's lane has one shooting spot).")
        for k in ("camera_fov", "camera_look_height", "title_cam_pos", "title_look_at", "title_drift", "title_period_s", "title_fov", "title_stars",
                  "sun_rotation_deg", "sun_energy", "sun_color", "ambient_color", "ambient_energy", "background_color", "fog_enabled", "fog_color", "fog_density", "ocean", "arcade_life", "top_wash"):
            v = field(k)
            if v != "—":
                out.append("- `%s` = %s" % (k, v))
        out.append("")
    return "\n".join(out) + "\n"


README = """# Hoop Shoot — the 3D areas, packed for a design session

Hoop Shoot is a first-person arcade pop-a-shot basketball game for Android
(Godot 4, portrait, 720×1280): you flick a ball at a hoop a few metres away,
on a clock, against the arcade's own machine, an AI league opponent or
another player online. Three **areas** exist. Each is a small 3D set the
player looks into from the shooting spot, with a title "pan" the home page
drifts through. This bundle is everything that makes those sets, so new
areas can be designed in the same direction.

## The three areas

- **Arcade cage** (`areas/cage`) — a dark arcade hall; the pop-a-shot machine
  is a chain-link cage in orange trim with a mesh roof, a padded egg-crate
  back wall, an LED scoreboard over the hoop and a full-width LED ribbon
  along the bottom, a return ramp under the hoop and a deck with yellow
  return arrows that chase back to the player, string lights along the top
  rails, the arcade hall (cabinets, carpet, hall lights) glimpsed through the
  mesh. Rim at 2.90 m. The junior board (1.22 × 0.76) slides in the last 30 s.
- **Beach** (`areas/beach`) — sunset over the ocean; a concrete street court
  on the sand with a palm or two, a street hoop on an in-ground pole with a
  nylon net, a fence around the court, boardwalk dressing (a boombox, a
  towel, a pelican). Rim 3.41 m out. Five shooting spots; the last 30 s walk
  you between them.
- **City court** (`areas/city`) — dusk in a city block: a fenced asphalt
  court among low-poly buildings (the third-party pack, re-graded into the
  palette), a chain-net hoop, a tabletop scoreboard and one floor speaker by
  the pole, a mural, posters, a tower on the skyline, cars passing on the
  street beyond the fence. Rim 3.63 m out, the bounciest iron. Five spots.

Snapshots of each, rendered from the real game camera, are in
`areas/<area>/area_<area>.png` (wide, the archive card) and
`area_<area>_tall.png` (portrait, the unlock page): these are the truth for
the look.

## The look (the rules we actually follow)

- **Low-poly, flat-shaded.** Every mesh is deliberately faceted (Shade Flat);
  no Subdivision Surface. A prop stays under a few hundred faces; the ball is
  the one smooth exception. Keep facets visible — add segments, don't smooth.
- **Pixel-art textures, nearest-filtered.** Small sheets drawn at final size
  (≈ 3 mm per pixel at the camera's distance), Closest interpolation in
  Blender, `TEXTURE_FILTER_NEAREST` in Godot. Photo sources (the buildings'
  atlas) are conformed through the Aseprite scripts into the same palette and
  crushed to the house colour depth — nothing under `assets/` is hand-edited.
- **The palette family.** Cream `#F1E8D0`, ink `#221C18`, orange `#E8703A`,
  gold `#F0B84A`, teal `#3F8C7A`, pine `#3E7C4F`, blue `#7FAEC6`, tan
  `#CDBF9C`, and per-area accents (the cage's orange trim and red tubes, the
  beach's sand / foam / sunset sky, the city's brick / asphalt / flood-light
  white). Materials are mostly flat colours (`mat_flat(name, rgb, roughness)`
  in the build scripts) with a texture only where it earns its place.
- **Lighting is per area**, set in `arena_set.tres`: one sun (rotation,
  energy, colour, shadows), an ambient colour and energy, a background colour,
  optional fog (the beach and city), and `top_wash` for a bright sky that
  needs an ink wash behind the HUD cards. The cage is dark with emissive
  nodes (`HallBack`); the beach is a warm 1.4 sun with pink fog; the city a
  cool 1.9 sun with faint fog.
- **Dithered shadows and checkerboards are UI language**, not world language.
  In the 3D sets, shadows come from the sun.

## Scale, the lane and the camera

See `docs/geometry.md` (generated from the code): every court shares a
2.44 m rim and a 1.85 m release height; they differ in hoop distance, iron
bounce, board size, enclosure and props. The player camera uses
`camera_fov` 60 and looks at `camera_look_height` 2.2. The title pan is
`title_cam_pos` → `title_look_at` drifting by `title_drift` over
`title_period_s` at `title_fov` 66. Spots are `spot_positions` (metres, the
key at the origin) with `spot_names`; areas get 1 / 2 / 3 `title_stars`.

## What a new area must ship

1. `areas/<id>/<id>.glb` built by a `build_<id>.py` in the house style (see
   `source/scripts/build_beach.py` for the simplest full area and
   `build_city.py` for one with imported props). The game binds nodes by
   name: the hoop's `Backboard`, `Rim`, `RimPivot`, `Net`, `Pole`, `Crossbar`,
   `BoardBand`, `LedFace` (the scoreboard LED strip) and, if the area has
   them, `LeagueFace` (a second LED ribbon — never named `LedFace`),
   `ScoreboardRig` / `ScoreClock` (the city's tabletop board), `Trolley` (the
   cage's moving board), `Speakers` / `Scoreboard` empties for props, and the
   `Spots` empties. The hoop itself comes from a hoop set (`hoops/`), not the
   area.
2. `arena_set.tres` with every field the cage's has (lighting, camera, title
   pose, stars, spots, `ocean` / `arcade_life` / `top_wash` flags, ambient
   clips).
3. A `SimGeometry` recipe in the game's physics: distance, rim restitution,
   board, enclosure bounds, pole, prop boxes that match what is drawn (the
   ball bounces where the fence is drawn, or it rebounds off thin air).
4. Three to five shooting spots and the last-30-s mechanic (a shuffle, or a
   moving board).
5. The two snapshots, rendered in-game.
6. A hoop set if the area wants its own iron and net (`hoops/street`,
   `hoops/chain` are the templates: a rim, a board, a net or chain, LED
   strips, make / miss sounds).

## How the existing ones were made

`source/scripts/build_<area>.py` is the source of truth for every model
(the `.blend` in `source/blender/` is its output, kept for inspection):

    /Applications/Blender.app/Contents/MacOS/Blender -b --python build_city.py -- --force

Each script builds the meshes from primitives and boxes, assigns flat
materials or the pixel textures in `textures/`, places the bound empties,
and exports the glb next to the game's `arena_set.tres`. The hoops, the
ball, the ice, the locker machine and the city's cars have their own scripts
in the same folder. `source/scripts/aseprite/` holds the texture pipeline
(palette conform, the buildings' atlas).

## Credits and licences

- `third_party/buildings`: Low Poly Buildings Pack by Sam Grady, CC BY 4.0
  (credit "Sam Grady"); used for the city's buildings. Full note in its
  `CREDITS.md`.
- `props/vehicles`: the city's cars came from a GGBot pack and are credited
  in the game's credits screen; the licence was not recorded at the time —
  treat them as reference, not as free to redistribute.
- Everything else in this bundle is Hoop Shoot's own work.

## What is not here

Audio (the areas' ambience, the hoops' make / miss clips), the Godot import
sidecars, Blender's `.blend1` backups, and the game code. The game lives in
the hoop_shoot repository; the physics that mirrors each court is
`core/physics/sim_geometry.gd` there.
"""


def main() -> int:
    out_dir = Path(sys.argv[1]).expanduser() if len(sys.argv) > 1 else Path.home() / "Desktop"
    tmp = Path(tempfile.mkdtemp(prefix="hs3d_"))
    root = tmp / NAME
    root.mkdir()
    counts = {}
    for area in ("cage", "beach", "park", "city"):
        dst = root / "areas" / area
        counts["areas/" + area] = copy_tree(ROOT / "assets/arena" / area, dst)
        counts["areas/" + area] += copy_files([ROOT / "assets/ui/areas" / ("area_%s.png" % area), ROOT / "assets/ui/areas" / ("area_%s_tall.png" % area)], dst)
    for hoop in ("classic", "street", "chain"):
        counts["hoops/" + hoop] = copy_tree(ROOT / "assets/hoops" / hoop, root / "hoops" / hoop)
    counts["balls"] = copy_tree(ROOT / "assets/balls/classic", root / "balls")
    counts["balls/skins"] = copy_tree(ROOT / "assets/textures/balls", root / "balls/skins")
    counts["balls/sets"] = sum(copy_files([p], root / "balls/sets" / p.parent.name) for p in sorted((ROOT / "assets/balls").glob("*/ball_set.tres")))
    counts["props"] = copy_files([ROOT / "assets/fx/rim_ice.glb", ROOT / "assets/locker/peggy.glb"], root / "props")
    counts["props"] += copy_tree(ROOT / "assets/locker", root / "props/peggy", keep=lambda p: p.suffix == ".png")
    counts["props/vehicles"] = copy_tree(ROOT / "assets/vehicles", root / "props/vehicles")
    counts["props/fx"] = copy_files(sorted((ROOT / "assets/textures").glob("fx_*.png")), root / "props/fx")
    counts["props/cards"] = copy_tree(ROOT / "assets/textures/cards", root / "props/cards")
    counts["textures"] = copy_files([p for p in sorted((ROOT / "assets/textures").glob("*.png")) if not p.name.startswith("fx_")], root / "textures")
    counts["source/blender"] = copy_tree(ROOT / "art/blender", root / "source/blender", keep=lambda p: p.suffix == ".blend")
    counts["source/scripts"] = copy_tree(ROOT / "tools/blender", root / "source/scripts", keep=lambda p: p.suffix == ".py")
    if (ROOT / "tools/aseprite").exists():
        counts["source/scripts/aseprite"] = copy_tree(ROOT / "tools/aseprite", root / "source/scripts/aseprite", keep=lambda p: p.suffix in (".lua", ".txt", ".md"))
    counts["third_party"] = copy_tree(ROOT / "art/third_party", root / "third_party")
    (root / "docs").mkdir()
    shutil.copy2(ROOT / "docs/BLENDER_101.md", root / "docs/BLENDER_101.md")
    counts["docs/img"] = copy_tree(ROOT / "docs/img", root / "docs/img") if (ROOT / "docs/img").exists() else 0
    (root / "docs/geometry.md").write_text(geometry_md())
    (root / "README.md").write_text(README)
    out_dir.mkdir(parents=True, exist_ok=True)
    for k in sorted(counts):
        print("%-24s %4d files" % (k, counts[k]))
    common = ["README.md", "docs"]
    ok = True
    for tag, groups in PARTS:
        out_zip = out_dir / ("%s_%s.zip" % (NAME, tag))
        if out_zip.exists():
            out_zip.unlink()
        with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED) as z:
            for g in common + groups:
                base = root / g
                files = [base] if base.is_file() else sorted(p for p in base.rglob("*") if p.is_file())
                for p in files:
                    z.write(p, p.relative_to(tmp))
        mb = out_zip.stat().st_size / 1e6
        flag = "" if mb <= PART_CAP_MB else "   ← OVER THE %.1f MB CAP: split the part" % PART_CAP_MB
        ok = ok and mb <= PART_CAP_MB
        print("WROTE %s (%.1f MB)%s" % (out_zip, mb, flag))
    shutil.rmtree(tmp)
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
